/** 고정 번호 중 도형(entity)인 것 */
export function isFixedEntityType(t: number): boolean {
  return (t >= 1 && t <= 41) || (t >= 43 && t <= 47) || t === 74 || t === 77 || t === 78 || t === 0x1f2;
}

